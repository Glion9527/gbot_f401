/* 本工程把定时器分为三种用途，当前这些定时器的输入时钟都是 84MHz：
 *
 * 1. TIM1 输出四路 PWM，给驱动板的 PWMA/B/C/D 调节电机驱动力。
 *    PWM 频率 = 定时器时钟 / (PSC+1) / (ARR+1)
 *             = 84MHz / (0+1) / (4199+1) = 20kHz，即每周期 50us。
 *    CH1 PA8 -> A/左前，CH2 PA9 -> B/左后，
 *    CH3 PA10 -> C/右后，CH4 PA11 -> D/右前。
 *    四通道频率相同，但各自的 CCR 比较值可分别设置，因此占空比可独立调节。
 *
 * 2. TIM2/3/4/5 接收四台电机的 AB 相编码器，负责“数轮子转了多少”。
 *    TIM2 -> B/左后 PA15、PB3；TIM3 -> A/左前 PA6、PA7；
 *    TIM4 -> C/右后 PB6、PB7；TIM5 -> D/右前 PA0、PA1。
 *    TI12 正交编码器模式利用两相信号的先后关系判断方向，并四倍频计数。
 *    这里的两路 RISING 配置不表示“只数 A 相上升沿”；实际由编码器模式译码。
 *    四路统一计数范围 0..65535，越过边界会回绕，motor4.c 用相邻读数的差
 *    还原有正负方向的增量，不需要每来一个编码器脉冲就进入中断。
 *
 * 3. TIM9 提供固定控制节拍：84MHz / (8399+1) / (99+1) = 100Hz。
 *    即每 10ms 进入一次中断，motor4.c 在回调中测速并执行四路 PI 调速。
 *
 * MX_TIMx_Init 只是配置硬件；真正启动 PWM/编码器的是 Motor4_Init，
 * 真正启动 TIM9 中断的是 main.c 中的 HAL_TIM_Base_Start_IT。
 */
